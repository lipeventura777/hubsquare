// Ícones próprios do ServSquare em estilo pixel (DESIGN.md, seção 6.11): cada um é uma grade 16×16,
// onde "#" é um pixel pintado na cor do texto (currentColor). Mostrados a 28px ou 16px.

type Props = { className?: string }

function caminho(mapa: string[]): string {
  let d = ''
  mapa.forEach((linha, y) => {
    for (const m of linha.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`
  })
  return d
}

function pixel(mapa: string[]): (p: Props) => React.JSX.Element {
  const d = caminho(mapa)
  return function Icone({ className = 'h-4 w-4' }: Props) {
    return (
      <svg
        viewBox={`0 0 ${mapa[0].length} ${mapa.length}`}
        aria-hidden="true"
        className={className}
        shapeRendering="crispEdges"
      >
        <path d={d} fill="currentColor" />
      </svg>
    )
  }
}

